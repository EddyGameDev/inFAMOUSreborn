#!/usr/bin/env python3
"""spu_ibfast.py -- v177 post-pass over register-cached lifted SPU code (spu_recomp_rc.c).

Every computed branch in lifted code (bi/biz/binz/selb-loop `bi rN`) used to leave the C function:
    ctx->pc = ctx->gpr[N]._u32[0]; g_spu_trampoline_fn = spu_indirect_branch; return;
and the drain loop ran the full resolver (spu_indirect_branch: refresh_ovl, cache, lookup, tlc) and re-entered.
The SPU compiler builds most inner loops that way (`rT = selb(rHead, r0, rCond); bi rT`), so every loop
ITERATION paid a full dispatch (prof176 SPU_IBSTAT: ~6 M/s on the SPURS kernel thread, ~25 % of its time).

This pass puts SPU_IBF_SITE(...) in front of each such line (spu_ibf.h):
  * target == this function's own entry  -> goto the top of the function (locals are current: the spill
    on the same path already wrote them back), no exit at all;
  * target == an entry of THIS module    -> direct musttail into it, via a per-site 32-bit cache
    (pc << 14 | table index) in front of a binary search over the module's address-sorted table;
  * anything else (PM code, special PCs, a pending interrupt, diagnostics, SPU_IBF=0) -> the old line.
Only WWS job modules (jobmod_*), whose code is the resident overlay while it runs. Idempotent (marker).
v178: also the indirect-call bracket (bisl): SPU_IBF_CALL calls the resolved entry directly.\nv185: `bi $r0` loop branches back to the own entry (SPU_IBF_RETSELF), for functions whose entry is an ila constant.
Usage: spu_ibfast.py <spu dir> [--undo]
"""
import os, re, sys
MARK = '/* v177 spu_ibfast */'
RET = re.compile(r'(?<!SPU_IBF_RETSELF\()\bSPU_RET\(ctx\);')   # v185
RETN = [0]
SITE = re.compile(r'ctx->pc = ctx->gpr\[(\d+)\]\._u32\[0\]; g_spu_trampoline_fn = spu_indirect_branch; return;')

def process(path, undo=False):
    s = open(path, encoding='utf-8', errors='surrogateescape').read()
    if MARK in s:
        orig = open(path + '.pre_ibf', encoding='utf-8', errors='surrogateescape').read()
        s = orig
        if undo:
            open(path, 'w', encoding='utf-8', errors='surrogateescape', newline='\n').write(s); os.remove(path + '.pre_ibf'); return 0, 0
    elif undo: return 0, 0
    else:
        open(path + '.pre_ibf', 'w', encoding='utf-8', errors='surrogateescape', newline='\n').write(s)
    m = re.search(r'^void (\w+?)_rc_spu_func_', s, re.M)
    if not m: return 0, 0
    P = m.group(1)
    # v185: candidate loop heads = entry addresses the module loads as constants (ila) -> SPU_RET self-loop sites
    ila = set(int(x, 16) for x in re.findall(r'spu_ila\(0x([0-9A-Fa-f]+)\)', s))
    lines = s.split('\n')
    head = re.compile(r'^(?:static\s+)?void\s+' + re.escape(P) + r'_rc_spu_func_([0-9A-Fa-f]{8})\(spu_context\*\s*ctx\)\s*\{\s*$')
    out = []; i = 0; nsite = 0; nfn = 0; k = 0
    while i < len(lines):
        l = lines[i]; hm = head.match(l)
        if not hm:
            out.append(l); i += 1; continue
        addr = int(hm.group(1), 16)
        j = i + 1
        while lines[j] != '}': j += 1
        body = lines[i + 1:j]
        retself = (addr in ila) and 0x4000 <= addr < 0x3E000 and addr != 0x4A40 and any(RET.search(b) for b in body)
        if not any(SITE.search(b) for b in body) and not retself:
            out.append(l); out.extend(body); i = j; continue
        # label after the leading declarations (LS base + u128 locals)
        d = 0
        while d < len(body) and (body[d].startswith('\tuint8_t* spu_rc_ls') or body[d].startswith('\tu128 ')): d += 1
        fn = '%s_rc_spu_func_%08X' % (P, addr)
        nb = body[:d] + ['spu_ibf_top: ;'] + body[d:]
        def rep(mm):
            global_k = rep.k; rep.k += 1
            return 'SPU_IBF_SITE(ctx, %s, 0x%Xu, %s, s_ibf_c[%d], %s_ibf_find) %s' % (mm.group(1), addr, fn, global_k, P, mm.group(0))
        rep.k = k
        nb2 = []
        for b in nb:
            b2, n = SITE.subn(rep, b); nsite += n
            if retself:
                b2, n2 = RET.subn('SPU_IBF_RETSELF(ctx, 0x%Xu, %s) SPU_RET(ctx);' % (addr, fn), b2); nsite += n2; RETN[0] += n2
            nb2.append(b2)
        k = rep.k
        out.append(l); out.extend(nb2); nfn += 1; i = j
    src = '\n'.join(out)
    # v178: indirect CALL brackets (bisl) -> SPU_IBF_CALL
    CALL = re.compile(r'ctx->pc = _bt; ctx->host_depth\+\+; spu_indirect_branch\(ctx\);')
    def crep(mm):
        nonlocal k
        r = 'ctx->pc = _bt; ctx->host_depth++; SPU_IBF_CALL(ctx, s_ibf_c[%d], %s_ibf_find)' % (k, P); k += 1
        return r
    src, ncall = CALL.subn(crep, src)
    nsite += ncall
    if not nsite: return 0, 0
    # module function table (static, generated by the lifter) -> sorted search helper at the end
    tab = re.findall(r'\{ 0x([0-9A-Fa-f]{8})u, ' + re.escape(P) + r'_rc_spu_func_([0-9A-Fa-f]{8}), ', src)
    ent = sorted(set((int(a, 16), f) for a, f in tab if a.upper() == f.upper()))
    assert ent, 'no function table in ' + path
    assert len(ent) < 0x3FFE, 'too many entries for the 14-bit cache index'
    pre = ['#include "spu_ibf.h"   ' + MARK,
           'static SPU_THREAD_LOCAL uint32_t s_ibf_c[%d];   /* per-site cache: pc << 14 | index + 1 (v187: per thread -- a shared array was written by every lane running the module: false sharing, perf189 w6 22 %% on its first load) */' % k,
           'static spu_ibf_fn %s_ibf_find(uint32_t pc, uint32_t* c);' % P]
    inc = re.search(r'^#include "spu_helpers_vec\.h".*$', src, re.M)
    src = src[:inc.end()] + '\n' + '\n'.join(pre) + src[inc.end():]
    # v186: hashed lookup + negative per-site cache (was: binary search on every per-site cache miss, and no
    # caching of misses -- sites whose target is not an entry of this module searched the whole table every time;
    # perf188 "spu" profile: jobmod_50f371dc382d ibf_find above every function of that module).
    H = 1
    while H < 4 * len(ent): H *= 2
    hk = [0] * H; hv = [0] * H
    for idx, (a_, _) in enumerate(ent):
        h = (((a_ >> 2) * 0x9E3779B1) & 0xFFFFFFFF) >> (32 - (H.bit_length() - 1))
        while hk[h]: h = (h + 1) & (H - 1)
        hk[h] = a_; hv[h] = idx + 1
    hb = H.bit_length() - 1
    post = ['', '/* v177 spu_ibfast: this module\'s entries (v186: open-addressing hash, %d slots) */' % H,
            'static const uint32_t s_ibf_hk[%d] = {%s};' % (H, ','.join('0x%Xu' % x for x in hk)),
            'static const uint16_t s_ibf_hv[%d] = {%s};' % (H, ','.join('%d' % x for x in hv)),
            'static const spu_ibf_fn s_ibf_fn[%d] = {%s};' % (len(ent), ','.join('%s_rc_spu_func_%s' % (P, f) for _, f in ent)),
            'static spu_ibf_fn %s_ibf_find(uint32_t pc, uint32_t* c)' % P,
            '{',
            '    const uint32_t v = __atomic_load_n(c, __ATOMIC_RELAXED);',
            '    if (v && (v >> 14) == pc) { const uint32_t i = v & 0x3FFFu; return i == 0x3FFFu ? 0 : s_ibf_fn[i - 1u]; }',
            '    uint32_t r = 0x3FFFu;   /* not an entry of this module (cached too: the table is static) */',
            '    if (spu_ibf_pc_ok(pc)) {',
            '        uint32_t h = ((pc >> 2) * 0x9E3779B1u) >> %d;' % (32 - hb),
            '        for (;;) { const uint32_t k = s_ibf_hk[h]; if (k == pc) { r = s_ibf_hv[h]; break; } if (!k) break; h = (h + 1u) & %du; }' % (H - 1),
            '    }',
            '    __atomic_store_n(c, (pc << 14) | r, __ATOMIC_RELAXED);',
            '    return r == 0x3FFFu ? 0 : s_ibf_fn[r - 1u];',
            '}', '']
    src = src.rstrip('\n') + '\n' + '\n'.join(post)
    open(path, 'w', encoding='utf-8', errors='surrogateescape', newline='\n').write(src)
    return nsite, nfn

def main():
    root = sys.argv[1]; undo = '--undo' in sys.argv; ts = tf = 0
    for d in sorted(os.listdir(root)):
        if not d.startswith('jobmod_'): continue
        p = os.path.join(root, d, 'spu_recomp_rc.c')
        if not os.path.isfile(p): continue
        ns, nf = process(p, undo); ts += ns; tf += nf
        print('%-32s %4d sites in %4d functions (%d ret-self)' % (d, ns, nf, RETN[0])); RETN[0] = 0
    print('total', ts, 'sites', tf, 'functions', '(undone)' if undo else '')
if __name__ == '__main__': main()
