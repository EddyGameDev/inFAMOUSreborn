#!/usr/bin/env python3
"""v133 (v137: + fixed-address job-manager stubs, prefilter, per-thread stats): lift inFamous' WWS "plugin" blobs (position-independent SPU code embedded in the EBOOT, DMA'd into job
buffers at a different LS address for every job and called from jobmod_6cbbde2f1bfc via its LS 0xE864 table) into
RELOCATABLE C (spu_lifter.py --reloc semantics), plus a runtime lookup that recognises a loaded blob by content.

Usage: plug_lift.py EBOOT.elf OUTDIR [observed_entries.json]
Blobs are found by their header: +0x10 code size, +0x14 total size, +0x1C == 0x40, +0x2C == 1 (+0x28 is patched at
load time; the last 16 bytes are writable data). Function starts: 0x30, header entries (+0x18/+0x20/+0x24), observed
runtime entry offsets, brsl targets, the instruction after each unconditional return/jump, and every direct branch
target that leaves a function (fixpoint)."""
import sys, os, json, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from spu_disasm import disassemble_spu
import spu_lifter as L

def find_blobs(eb):
    w = lambda a: struct.unpack('>I', eb[a:a+4])[0]
    out = []
    for b in range(0, len(eb) - 0x30, 16):
        if w(b+0x1c) == 0x40 and w(b+0x2c) == 1 and w(b+0x28) == 0 and 0x30 < w(b+0x10) <= w(b+0x14) < 0x20000 \
           and w(b+0x20) < w(b+0x14) and w(b+0x24) < w(b+0x14) and w(b+0x18) < w(b+0x14):
            out.append(dict(file=b, code=w(b+0x10), size=w(b+0x14), e18=w(b+0x18), e20=w(b+0x20), e24=w(b+0x24)))
    return out

# v137: FIXED-address code regions lifted the same way (lookup checks base == 0, i.e. the exact LS address, and the
# function's own bytes). Remaining interpreter hot spots after v136 (play136, 10 s, all lanes):
#   0x3FEC0  context-restore stub the WWS job manager (pm_wwsjob) GENERATES at run time: lqa $0..$75, bi $79
#            (~0.9 s interpreted per 10 s; identical in all 90 LS dumps)
#   0x00A2C  pm_wwsjob's resume path after the job yields (computed entry, not an entry of the pm_wwsjob lift):
#            builds that stub, brasl's to it, then calls 0x2360 (~0.3 s / 10 s)
CTX_RESTORE = bytes.fromhex(''.join('30ff%02x%02x' % (0x38 + 2 * r, r) for r in range(76)) + '35002780')
# v138: the SAVE variant pm_wwsjob's 0xA2C path generates in the same place (stqa $0..$75; bi $79): play137 showed
# 0x3FEC0 still interpreted ~0.5 s / 10 s with the restore variant lifted -> both are lifted, the bytes decide.
CTX_SAVE = bytes.fromhex(''.join('20ff%02x%02x' % (0x38 + 2 * r, r) for r in range(76)) + '35002780')
FIXED = [
    # (name, LS org, bytes-source, extra starts)
    ('pmA2C', 0xA2C, ('eboot', 0x68C380 + 0xA2C, 0x64), ()),
    ('ctxrest', 0x3FEC0, ('const', None, None), ()),
    ('ctxsave', 0x3FEC0, ('const2', None, None), ()),
]

def fnv32(bs):
    h = 2166136261
    for x in bs: h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h

def main():
    ebp, outdir = sys.argv[1], sys.argv[2]
    obs = json.load(open(sys.argv[3])) if len(sys.argv) > 3 else {}
    eb = open(ebp, 'rb').read()
    blobs = find_blobs(eb)
    os.makedirs(outdir, exist_ok=True)
    src = ['/* Auto-generated by tools/plug_lift.py (v133) -- relocatable lift of the WWS plugin blobs. Do not edit. */',
           '#include "spu_recomp.h"', '#include "../../runtime/spu/spu_helpers.h"', '#include <string.h>', '#include <stdio.h>', '']
    hdr = ['/* Auto-generated by tools/plug_lift.py (v133). */', '#pragma once',
           '#include "../../runtime/spu/spu_context.h"', '#ifdef __cplusplus', 'extern "C" {', '#endif',
           L.HEADER_PREAMBLE.split('#ifdef __cplusplus\nextern "C" {\n#endif', 1)[1].rsplit('#ifdef __cplusplus', 1)[0],
           '#if defined(_MSC_VER)', '#define SPU_PLUG_TLS __declspec(thread)', '#else', '#define SPU_PLUG_TLS _Thread_local', '#endif',
           'extern SPU_PLUG_TLS uint32_t g_spu_frag_delta;   /* runtime LS base of the blob being run */',
           'typedef void (*spu_plug_fn)(spu_context*);',
           'spu_plug_fn spu_plug_lookup(spu_context* ctx, uint32_t pc);']
    entries = []   # (hash32, blob, off, flen, fn)
    blobdata = []  # (k, org, image bytes, header check length, fixed)
    report = []
    items = []
    for k, bl in enumerate(blobs):
        raw = eb[bl['file']:bl['file'] + bl['size']]
        dend = bl['size'] - 0x10                      # last quad = writable data
        st = {0x30}
        for e in (bl["e18"], bl["e20"], bl["e24"], bl["code"]):
            if 0x30 <= e < dend and e % 4 == 0: st.add(e)
        for o in obs.get(str(k), []):
            if 0x30 <= o < dend: st.add(o)
        items.append(dict(name='blob', file=bl['file'], raw=raw, org=0, lo=0x30, hi=dend, hdr=0x28, fixed=False, starts=st,
                          img=raw[:dend]))
    for name, org, srcd, extra in FIXED:
        if srcd[0] == 'eboot':
            n = srcd[2]; raw = eb[srcd[1]:srcd[1] + n + 0x20]       # +0x20: the 32-byte hash window may run past the end
        else:
            raw = CTX_RESTORE if srcd[0] == 'const' else CTX_SAVE; n = len(raw)
        items.append(dict(name=name, file=srcd[1] or 0, raw=raw, org=org, lo=org, hi=org + n, hdr=0, fixed=True,
                          starts={org, *extra}, img=raw))
    fn_first = len(src)
    for k, it in enumerate(items):
        raw, org, lo, dend = it['raw'], it['org'], it['lo'], it['hi']
        size = len(raw)
        insns = [i for i in disassemble_spu(raw, org) if lo <= i.addr < dend]
        by = {i.addr: i for i in insns}
        starts = set(it['starts'])
        for i in insns:
            t = L.SPULifter._branch_target(i)
            if i.mnemonic in ('brsl',) and t is not None and lo <= t < dend and t != i.addr + 4 and t != i.addr:
                starts.add(t)
            # v134b: every call's RETURN ADDRESS is an entry too: after an interrupt unwind (spu_restart_dispatch) or
            # when the caller ran in the interpreter, the callee's `bi $0` dispatches to it instead of returning
            # into a live host frame. Without an entry there the interpreter took the rest of the plugin call.
            if i.mnemonic in ('brsl', 'bisl', 'brasl') and i.addr + 4 < dend and t != i.addr + 4:
                starts.add(i.addr + 4)
            if i.mnemonic in ('bi', 'br') and i.addr + 4 < dend:
                nxt = by.get(i.addr + 4)
                if nxt is not None and nxt.mnemonic not in ('.word', 'stop', 'stopd', 'lnop', 'nop'):
                    starts.add(i.addr + 4)
        # fixpoint: direct branch targets that leave their function become starts
        for _ in range(20):
            ss = sorted(starts); bounds = list(zip(ss, ss[1:] + [dend]))
            new = set()
            for s, e in bounds:
                for i in insns:
                    if s <= i.addr < e:
                        t = L.SPULifter._branch_target(i)
                        if t is not None and lo <= t < dend and not (s <= t < e) and t not in starts and t % 4 == 0:
                            new.add(t)
            if not new: break
            starts |= new
        ss = sorted(starts); bounds = list(zip(ss, ss[1:] + [dend]))
        lf = L.SPULifter(prefix=f"wwsplug{k:02d}_")
        lf.reloc = True
        allins = [i for i in disassemble_spu(raw, org) if i.addr < dend]
        lf.bi_r0_jump = L.compute_bi_r0_jumps(allins, bounds)
        lf.link_return = L.compute_link_returns(allins, bounds)
        lf.func_starts = set(ss)
        if it['fixed']:
            # v137: a fixed region may end mid-function (pmA2C ends where the pm_wwsjob lift's 0xA90 starts): chain to
            # the address after it through an indirect-dispatch stub instead of silently returning.
            lf.func_starts.add(dend)
        for s, e in bounds:
            lf.lift_function(allins, s, e)
        if it['fixed']:
            lf.branch_targets.add(dend)
        body = lf.emit_source('spu_recomp.h').split('\n')
        # keep only function bodies + extern stubs (drop preamble, table, register)
        cut = body.index('/* Function table */')
        pre_end = 0
        while pre_end < len(body) and not body[pre_end].startswith('void '):
            pre_end += 1
        src.append(f'/* ---- blob {k} ({it["name"]}{", fixed LS 0x%X" % org if it["fixed"] else ""}): file 0x{it["file"]:X}, size 0x{size:X}, {len(lf.functions)} functions ---- */')
        src.extend(body[pre_end:cut])
        for f in lf.functions:
            hdr.append(f'void {f.name}(spu_context* ctx);')
        for t in sorted((lf.call_targets | lf.branch_targets) - {f.start_addr for f in lf.functions}):
            hdr.append(f'void wwsplug{k:02d}_spu_func_{t:08X}(spu_context* ctx);')
        for s, e in bounds:
            flen = min(e - s, 0x800)
            h = fnv32(raw[s - org:s - org + 32])
            assert len(raw[s - org:s - org + 32]) == 32
            entries.append((h, k, s, flen, f"wwsplug{k:02d}_spu_func_{s:08X}"))
        blobdata.append((k, org, it['img'], it['hdr'], it['fixed']))
        report.append((k, it['file'], size, len(lf.functions), dict(lf.unsupported)))
    # v137: register-cached twin of every lifted plugin function (tools/spu_regcache.py, as for the job modules:
    # SPU registers in host locals, spilled/reloaded around every runtime call) -> spu_recomp_rc.c beside it
    # (CMake PORT_SPU_REGCACHE compiles it). The table carries both; ABX 0x02 serves the rc copy.
    import re as _re, spu_regcache as RC
    fn_text = '\n'.join(src[fn_first:])
    rc_text, rc_n = RC.xform_file(fn_text)
    ren = _re.compile(r'\b(wwsplug\d\d)_spu_func_')
    rc_text = ren.sub(lambda m: m.group(1) + '_rc_spu_func_', rc_text)
    fnames = _re.findall(r'^void (wwsplug\d\d_spu_func_[0-9A-F]+)\(spu_context\* ctx\) \{$', fn_text, _re.M)
    rc_src = ['/* GENERATED by tools/plug_lift.py (v137) through spu_regcache.py: register-cached twins of the lifted WWS',
              ' * plugin functions in spu_recomp.c (same file layout as the job modules\' spu_recomp_rc.c). Do not edit. */',
              '#include "spu_recomp.h"', '#include "../../runtime/spu/spu_helpers.h"', '#include "spu_helpers_vec.h"', '']
    rc_src.append(rc_text)
    for n in fnames:
        hdr.append('void ' + ren.sub(lambda m: m.group(1) + '_rc_spu_func_', n) + '(spu_context* ctx);')
    print('rc: %d functions register-cached, %d twins' % (rc_n, len(fnames)))
    # blob bytes (header magic + code) for verification
    src.append('/* ---- blob images (verification) ---- */')
    for k, org, raw, hl, fx in blobdata:
        src.append(f'static const uint8_t s_plug_img{k:02d}[0x{len(raw):X}] = {{')
        for i in range(0, len(raw), 32):
            src.append('    ' + ','.join(str(x) for x in raw[i:i+32]) + ',')
        src.append('};')
    src.append('static const uint8_t* const s_plug_img[] = { ' + ', '.join(f's_plug_img{k:02d}' for k, *_ in blobdata) + ' };')
    src.append('static const uint32_t s_plug_org[] = { ' + ', '.join(f'0x{org:X}u' for k, org, *_ in blobdata) + ' };')
    src.append('static const uint8_t s_plug_hdr[] = { ' + ', '.join(f'0x{hl:X}' for k, org, raw, hl, fx in blobdata) + ' };')
    src.append('static const uint8_t s_plug_fixed[] = { ' + ', '.join(str(int(fx)) for *_, fx in blobdata) + ' };')
    entries.sort()
    # v137 prefilter: one bit per hashed first instruction word of every entry (8 KB); most misses stop here
    pf = [0] * 2048
    for h, k, s, flen, fn in entries:
        org, raw = blobdata[k][1], blobdata[k][2]
        w = struct.unpack('<I', raw[s - org:s - org + 4])[0]     # host (little-endian) load of the LS bytes
        b = ((w * 0x9E3779B1) & 0xFFFFFFFF) >> 16
        pf[b >> 5] |= 1 << (b & 31)
    src.append('static const uint32_t s_plug_pf[2048] = {')
    for i in range(0, 2048, 16):
        src.append('    ' + ','.join(f'0x{x:08X}u' for x in pf[i:i+16]) + ',')
    src.append('};')
    src.append('typedef struct { uint32_t h, off; uint16_t blob, len; spu_plug_fn fn, fn_rc; } spu_plug_entry;')
    src.append(f'static const spu_plug_entry s_plug_tab[{len(entries)}] = {{')
    for h, k, s, flen, fn in entries:
        src.append(f'    {{ 0x{h:08X}u, 0x{s:X}u, {k}, 0x{flen:X}, {fn}, {fn.replace("_spu_func_", "_rc_spu_func_")} }},')
    src.append('};')
    src.append(r'''SPU_PLUG_TLS uint32_t g_spu_frag_delta;
/* [plug] every ~10 s: lifted plugin calls served vs resolver misses that fell through (any code, not only plugins).
 * v137: per-thread counters, flushed every 4096 lookups (v136 did two contended atomics + GetTickCount64 on EVERY
 * lookup, ~2-20 M per 10 s from all lanes). */
#if defined(_WIN32)
#include <windows.h>
#endif
static volatile long s_plug_ok, s_plug_no, s_plug_amb; static volatile long long s_plug_t0;
static SPU_PLUG_TLS unsigned t_plug_ok, t_plug_no;
static void plug_flush(void)
{
    InterlockedExchangeAdd(&s_plug_ok, (long)t_plug_ok); InterlockedExchangeAdd(&s_plug_no, (long)t_plug_no);
    t_plug_ok = t_plug_no = 0;
    long long now = (long long)GetTickCount64();
    if (!s_plug_t0) s_plug_t0 = now;
    if (now - s_plug_t0 >= 10000 && InterlockedExchange64((volatile long long*)&s_plug_t0, now) != now) {
        extern volatile int g_abx; extern volatile long g_spu_plug_rejoins;
        fprintf(stderr, "[plug] 10s: %ld lifted plugin calls served, %ld other resolver misses, %ld interpreter hand-backs, %ld ambiguous (abx 0x%02X)\n",
                InterlockedExchange(&s_plug_ok, 0), InterlockedExchange(&s_plug_no, 0), InterlockedExchange(&g_spu_plug_rejoins, 0),
                InterlockedExchange(&s_plug_amb, 0), g_abx);
    }
}
static inline void plug_stat(int ok)
{
    if (ok) t_plug_ok++; else t_plug_no++;
    if (((t_plug_ok + t_plug_no) & 4095u) == 0) plug_flush();
}
static uint32_t plug_fnv32(const uint8_t* p) { uint32_t h = 2166136261u; for (int i = 0; i < 32; i++) h = (h ^ p[i]) * 16777619u; return h; }
/* A lifted function is served only when the blob header (PIC blobs: first 0x28 bytes: magic + layout; +0x28 is patched
 * at load time) AND the function's own instruction bytes at pc match the image exactly; anything else (another blob, a
 * partly overwritten buffer, an unseen variant) returns NULL and the interpreter runs it as before.
 * v137: FIXED regions (s_plug_fixed: job-manager stubs at their exact LS address; ABX bit 0x01) match only at that
 * address; a first-word bitmap rejects most misses before hashing. */
spu_plug_fn spu_plug_lookup(spu_context* ctx, uint32_t pc)
{
    pc &= SPU_LS_MASK;
    if (pc + 32 > SPU_LS_SIZE) return 0;
    { uint32_t w; memcpy(&w, ctx->ls + pc, 4); const uint32_t b = (w * 0x9E3779B1u) >> 16;
      if (!(s_plug_pf[b >> 5] & (1u << (b & 31)))) { plug_stat(0); return 0; } }
    extern volatile int g_abx;
    const uint32_t h = plug_fnv32(ctx->ls + pc);
    int lo = 0, hi = (int)(sizeof s_plug_tab / sizeof s_plug_tab[0]) - 1;
    while (lo < hi) { int m = (lo + hi) >> 1; if (s_plug_tab[m].h < h) lo = m + 1; else hi = m; }
    const spu_plug_entry* hit = 0; uint32_t hit_base = 0;
    for (int i = lo; i < (int)(sizeof s_plug_tab / sizeof s_plug_tab[0]) && s_plug_tab[i].h == h; i++) {
        const spu_plug_entry* e = &s_plug_tab[i];
        uint32_t base;
        if (s_plug_fixed[e->blob]) { if (pc != e->off || !(g_abx & 0x01)) continue; base = 0; }
        else { if (pc < e->off) continue; base = pc - e->off; }
        if (pc + e->len > SPU_LS_SIZE) continue;
        const uint8_t* img = s_plug_img[e->blob];
        if (s_plug_hdr[e->blob] && memcmp(ctx->ls + base, img, s_plug_hdr[e->blob]) != 0) continue;
        if (memcmp(ctx->ls + pc, img + (e->off - s_plug_org[e->blob]), e->len) != 0) continue;
        /* v139: keep scanning the hash group -- if a SECOND candidate (another blob or another base) also
         * verifies, the bytes at pc are shared code (e.g. the same helper linked into several plugins, or a
         * stale copy of the same blob still in the buffer) and the base is ambiguous: a wrong base relocates
         * every relative access. Let the interpreter run it. (0 cases in the 90 dumps; cheap insurance.) */
        if (hit && (hit->blob != e->blob || hit_base != base)) { InterlockedIncrement(&s_plug_amb); plug_stat(0); return 0; }
        hit = e; hit_base = base;
    }
    if (hit) {
        g_spu_frag_delta = hit_base;
        plug_stat(1);
        return (g_abx & 0x02) ? hit->fn_rc : hit->fn;   /* v137: ABX 0x02 = register-cached copy */
    }
    plug_stat(0);
    return 0;
}''')
    hdr += ['#ifdef __cplusplus', '}', '#endif', '']
    open(os.path.join(outdir, 'spu_recomp.h'), 'w').write('\n'.join(hdr))
    open(os.path.join(outdir, 'spu_recomp.c'), 'w').write('\n'.join(src) + '\n')
    open(os.path.join(outdir, 'spu_recomp_rc.c'), 'w', newline='\n').write('\n'.join(rc_src) + '\n')
    for r in report: print('blob %d file 0x%X size 0x%X: %d functions, unsupported %s' % r)
    print(len(entries), 'entries')

if __name__ == '__main__':
    main()
